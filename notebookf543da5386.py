# ==========================================
# Machine Learning: Select Target Variable
# ==========================================

print("Dataset Columns:\n")

for col in df.columns:
    print(col)

print("\nData Types:\n")
print(df.dtypes)

# -------------------------------------------------
# Choose a classification target
# -------------------------------------------------

target_column = None

possible_targets = [
    "Category",
    "category",
    "Beverage_category",
    "Beverage Category",
    "Drink Category"
]

for col in possible_targets:
    if col in df.columns:
        target_column = col
        break

if target_column is None:
    print("\nNo obvious classification target was found.")
    print("A Decision Tree Classifier cannot be built unless a categorical target exists.")
    print("Consider creating a target or using DecisionTreeRegressor instead.")

else:
    print(f"\nSelected Target Variable: {target_column}")

# ==========================================
# Data Preparation
# ==========================================

if target_column is not None:

    # Separate features and target
    X = df.drop(columns=[target_column])
    y = df[target_column]

    # Fill missing values
    for col in X.columns:

        if X[col].dtype == "object":
            X[col] = X[col].fillna(X[col].mode()[0])

        else:
            X[col] = X[col].fillna(X[col].median())

    # Encode categorical features
    X = pd.get_dummies(X, drop_first=True)

    # Encode target labels
    from sklearn.preprocessing import LabelEncoder

    label_encoder = LabelEncoder()

    y = label_encoder.fit_transform(y)

    print("Features shape:", X.shape)
    print("Target shape:", y.shape)

# ==========================================
# Split Dataset
# ==========================================

from sklearn.model_selection import train_test_split

X_train, X_test, y_train, y_test = train_test_split(
    X,
    y,
    test_size=0.20,
    random_state=42,
    stratify=y
)

print("Training Samples:", X_train.shape[0])
print("Testing Samples:", X_test.shape[0])

# ==========================================
# Train Decision Tree
# ==========================================

from sklearn.tree import DecisionTreeClassifier

model = DecisionTreeClassifier(
    random_state=42,
    max_depth=5
)

model.fit(X_train, y_train)

print("Decision Tree Model Trained Successfully.")

# ==========================================
# Predictions
# ==========================================

y_pred = model.predict(X_test)

# ==========================================
# Model Evaluation
# ==========================================

from sklearn.metrics import (
    accuracy_score,
    confusion_matrix,
    classification_report
)

accuracy = accuracy_score(y_test, y_pred)

print("Accuracy Score")
print(accuracy)

print("\nConfusion Matrix")
print(confusion_matrix(y_test, y_pred))

print("\nClassification Report")
print(classification_report(y_test, y_pred))

# ==========================================
